const DATA_ANALYSIS = `---
name: data-analysis
description: 数据分析技能：对表格/CSV/JSON 数据做清洗、统计描述、对比与归因分析，输出结论先行的分析报告（关键发现、支撑数字、建议行动）。当用户需要分析数据、找原因、看变化、做对比、解读指标时使用。
---

# 数据分析

## 流程（固定顺序）

1. **数据体检** — 行数/列数/类型/缺失/重复，发现异常先报告（"第 3 列 12% 缺失，将按中位数填补"），不静默处理。
2. **描述统计** — 数值列：均值/中位数/极值/标准差；类别列：频次 Top5。只报告与分析问题相关的列。
3. **对比与拆解** — 按用户关心的维度分组对比；变化类问题做加法拆解（量×价、人数×人均），指出主贡献项。
4. **结论** — 三层：关键发现（≤3 条，每条一句）→ 支撑数字（发现引用的具体数据）→ 建议行动（可选，标注"供参考"）。

## 必守规则

- **结论先行**：报告第一行就是关键发现，数据在后面支撑，不倒叙"我做了什么"。
- 相关不等于因果：只能说"A 与 B 相关/同期变化"，除非有实验或明确机制，并说明置信度。
- 样本量 < 30 的分组差异必须标注"样本量小，结论仅供参考"。
- 缺失率 > 40% 的列不参与分析，报告并说明。
- 处理工具优先级：能一行算清楚的用表达式；数据量大或需分组聚合时写 Python（pandas）执行；永远不手算超过 20 个数字的统计。

## 输出格式

## 关键发现 → ## 支撑数据 → ## 建议（供参考），三层递进。
`

